const GAME_ID = "game-celtics"
const PERIOD = "Q3"
const CLOCK = "5:46"

const HUSTLE = {
  contestedShots: 6,
  contestedShots2pt: 4,
  contestedShots3pt: 2,
  deflections: 3,
  screenAssists: 2,
  screenAssistPoints: 4,
  boxOuts: 2,
  offensiveBoxOuts: 1,
  defensiveBoxOuts: 1,
  looseBallsRecoveredTotal: 1,
  looseBallsRecoveredOffensive: 0,
  looseBallsRecoveredDefensive: 1,
  chargesDrawn: 0,
  boxOutPlayerTeamRebounds: 1,
  boxOutPlayerRebounds: 1,
}

function profileFromBox(
  id: string,
  name: string,
  teamAbbr: string,
  opponentAbbr: string,
  v: Record<string, string | number>,
  meta: {
    gameScore: number
    seasonAvgGameScore: number
    seasonGameScoreRank: number
    status?: "on court" | "bench"
    tsPct?: string
    efgPct?: string
    usgPct?: string
    pie?: string
  },
): PlayerLive {
  const fgm = Number(v.fgm)
  const fga = Number(v.fga)
  const fg3m = Number(v.fg3m)
  const fg3a = Number(v.fg3a)
  const ftm = Number(v.ftm)
  const fta = Number(v.fta)

  return {
    id,
    kind: "followed-player",
    name,
    gameId: GAME_ID,
    teamAbbr,
    opponentAbbr,
    minutes: Number(v.min),
    status: meta.status ?? "on court",
    period: PERIOD,
    clock: CLOCK,
    pts: Number(v.pts),
    fg: `${fgm}/${fga}`,
    fgPct: String(v.fg_pct),
    fg3: `${fg3m}/${fg3a}`,
    fg3Pct: String(v.fg3_pct),
    ft: `${ftm}/${fta}`,
    ftPct: String(v.ft_pct),
    oreb: Number(v.oreb),
    dreb: Number(v.dreb),
    reb: Number(v.reb),
    ast: Number(v.ast),
    tov: Number(v.tov),
    stl: Number(v.stl),
    blk: Number(v.blk),
    pf: Number(v.pf),
    plusMinus: String(v.plus_minus),
    gameScore: meta.gameScore,
    seasonAvgGameScore: meta.seasonAvgGameScore,
    seasonGameScoreRank: meta.seasonGameScoreRank,
    seasonGameScoreRankTotal: 312,
    tsPct: meta.tsPct ?? ".540",
    efgPct: meta.efgPct ?? ".520",
    usgPct: meta.usgPct ?? "24.0",
    astPct: "22.0",
    astToTov: "2.50",
    orebPct: "3.5",
    drebPct: "14.0",
    pie: meta.pie ?? ".120",
    ...HUSTLE,
  }
}

