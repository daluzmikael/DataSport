export function getPlayerProfile(playerId: string): PlayerLive | undefined {
  const live = LIVE_FEED.find(
    (i): i is PlayerLive => i.id === playerId && i.kind === "followed-player",
  )
  if (live) return live
  const past = PAST_PLAYER_PROFILES.find((p) => p.id === playerId)
  if (past) return past
  const game = GAME_PLAYER_PROFILES.find((p) => p.id === playerId)
  if (game) return game
  return OFFLINE_PLAYER_PROFILES.find((p) => p.id === playerId)
}

