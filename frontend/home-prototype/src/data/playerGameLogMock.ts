/** Maps game-log row ids to overlay game ids. */
export function gameLogRowToGameId(rowId: string): string {
  if (rowId === "live") return "game-celtics"
  const match = /^gl-(\d+)$/.exec(rowId)
  if (match) return `game-${match[1].replace(/\D/g, "").padStart(10, "0")}`
  return "game-celtics-yesterday"
}

