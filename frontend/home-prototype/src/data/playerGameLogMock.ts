function mapPast<T extends Record<string, string | number>>(
  games: Omit<GameLogRow, "isLive">[],
  mapper: (g: Omit<GameLogRow, "isLive">) => T,
): GameLogRow[] {
  return games.map((g) => ({
    id: g.id,
    isLive: false,
    game: g.game,
    values: mapper(g),
  }))
}

